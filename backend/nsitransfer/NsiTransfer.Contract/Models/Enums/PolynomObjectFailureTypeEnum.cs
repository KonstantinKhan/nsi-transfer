using System.ComponentModel;

namespace NsiTransfer.Contract.Models.Enums;

public enum PolynomObjectFailureTypeEnum
{
    /// <summary>
    /// Объект включён в несколько групп, у которых есть свойства MinValue и MaxValue.
    /// Невозможно однозначно определить, из какой группы брать код классификатора.
    /// </summary>
    [Description("Объект включён в несколько групп с MinValue/MaxValue")]
    MultipleGroupsWithMinMax = 1,

    /// <summary>
    /// Объект включён в одну группу, но у неё отсутствуют свойства MinValue и MaxValue.
    /// Группа должна иметь эти свойства.
    /// </summary>
    [Description("Группа не содержит свойств MinValue/MaxValue")]
    GroupWithoutMinMax = 2,

    /// <summary>
    /// Объект включён в группы, но ни одна из них не имеет свойств MinValue и MaxValue.
    /// Невозможно определить диапазон для вычисления кода классификатора.
    /// </summary>
    [Description("Отсутствуют группы с MinValue/MaxValue")]
    NoGroupsWithMinMax = 3,

    /// <summary>
    /// Объект не включён ни в одну группу в целом.
    /// </summary>
    [Description("Объект не включён ни в одну группу в целом")]
    NoGroupsAtAll = 4,

    /// <summary>
    /// Неизвестная ошибка валидации иерархии.
    /// Зарезервировано для будущих расширений алгоритма.
    /// </summary>
    [Description("Неизвестная ошибка валидации")]
    UnknownValidationError = 100,

    /// <summary>
    /// Объект не имеет свойства 'Код классификатора', хотя имеет понятие 'Данные классификатора'.
    /// </summary>
    [Description("Отсутствует свойство \'Код классификатора\' у объекта, у которого имеется понятие \'Данные классификатора\'")]
    CannotFindPropertyClassificationCode = 101,

    /// <summary>
    /// Произошла ошибка выполнения процесса по установке значения свойства 'Код классификатора'. Необходимо просмотреть логи сервиса.
    /// </summary>
    [Description("Произошла ошибка выполнения процесса по установке значения свойства \'Код классификатора\'. Необходимо просмотреть логи сервиса.")]
    ErrorWhileProcessWasExecuting = 102,

    /// <summary>
    /// Код классификатора объекта находится вне допустимого диапазона [MinValue, MaxValue] группы.
    /// Объект не находится в своей группе или код установлен некорректно.
    /// </summary>
    [Description("Код классификатора вне допустимого диапазона группы")]
    ClassificationCodeOutOfGroupRange = 103,

    /// <summary>
    /// Группа, в которой находится объект, содержит внутри себя другие группы (не является конечной).
    /// </summary>
    [Description("Группа объекта не является конечной (содержит вложенные подгруппы)")]
    GroupIsNotLeaf = 104
}
