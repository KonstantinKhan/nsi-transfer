-- =====================================================================
--  Примечания
-- =====================================================================
-- 1. Все timestamp with time zone хранят UTC (DateTime.UtcNow в коде).
--    Точность — 3 знака после секунды (HasPrecision(3)).
-- 2. SerializedMessage имеет DEFAULT '{}'::jsonb, чтобы CanBeNull + конвертер
--    в OnModelCreating не порождали NULL при пустом payload.
-- 3. PolynomObjectFailure.FailureType хранится строкой
--    (HasConversion<string>()), аналогично EmailMessage.Status.
-- 4. PolynomObjectId в PolynomObject — bigint (long), а в PolynomObjectFailure
--    — integer (int). Это историческое расхождение в миграциях.
-- 5. Каскадное удаление: Messages → PolynomObjects / PolynomObjectFailures /
--    MessageFailures; Sendings → Messages; EmailMessages → EmailFailures /
--    связку M:N. Удаление Sending'а зачищает всю его историю.
