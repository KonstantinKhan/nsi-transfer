--  Сгенерировано по: AppDbContext.OnModelCreating + AppDbContextModelSnapshot
--  EF Core 8.0.27 / Npgsql, провайдер identity-by-default
--  БД: nsi_transfer (см. ConnectionStrings:DefaultConnection)
